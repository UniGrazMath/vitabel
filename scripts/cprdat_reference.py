#!/usr/bin/env python
"""Generate reference outputs of ``Vitals.make_cprdat_analysis``.

``make_cprdat_analysis`` (the analysis used by the German Resuscitation
Registry) was developed on a feature branch, where it last worked at commit
``b2b678c``. It broke when it was merged into ``main`` (``e148f02``) because
the APIs it relies on had changed in the meantime.

This script checks out the last known-good commit in a temporary git
worktree, runs ``make_cprdat_analysis`` there (using the dependencies of the
*current* environment) on the test recordings, and stores the results as
compressed JSON in ``tests/data/golden``. They serve as reference material
when porting the function to the current API -- they are *not* golden files:
some differences are expected due to deliberate changes of the underlying
analysis routines since ``b2b678c``.

Usage::

    uv run python scripts/cprdat_reference.py [--ref b2b678c]
"""

from __future__ import annotations

import argparse
import bz2
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile

from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
DEFAULT_REF = "b2b678c"

RUNNER = r"""
import bz2, json, logging, platform, sys, warnings
from pathlib import Path

logging.disable(logging.CRITICAL)
warnings.filterwarnings("ignore")

import numpy as np, pandas as pd, sklearn
import vitabel
from vitabel import Vitals
from tests.golden import jsonable

worktree, case, recording_path, output_path, ref = sys.argv[1:6]
assert Path(vitabel.__file__).resolve().is_relative_to(Path(worktree).resolve()), (
    f"vitabel imported from unexpected location: {vitabel.__file__}"
)

recording = Vitals()
recording.add_defibrillator_recording(recording_path)
result = recording.make_cprdat_analysis()

content = {
    "description": (
        "Reference output of Vitals.make_cprdat_analysis at the last known-good "
        "commit. Generated by scripts/cprdat_reference.py; reference material, "
        "not a golden file."
    ),
    "case": case,
    "generated_with": {
        "git_ref": ref,
        "numpy": np.__version__,
        "pandas": pd.__version__,
        "scikit-learn": sklearn.__version__,
        "python": platform.python_version(),
        "platform": platform.platform(),
    },
    "result": jsonable(result),
}
with bz2.open(output_path, "wt", encoding="utf-8") as fd:
    json.dump(content, fd, indent=1)
print(f"{case}: wrote {output_path}")
"""


def _prepare_cases(tmpdir: Path) -> dict[str, Path]:
    zoll_path = tmpdir / "ZOLL_test_case.json"
    with (
        bz2.open(REPO_ROOT / "examples" / "data" / "ZOLL_test_case.json.bz2") as src,
        open(zoll_path, "wb") as dst,
    ):
        shutil.copyfileobj(src, dst)

    lifepak_dir = tmpdir / "lifepak"
    with tarfile.open(REPO_ROOT / "tests" / "data" / "LP15.tar.gz", "r:gz") as tar:
        if hasattr(tarfile, "data_filter"):
            tar.extractall(lifepak_dir, filter="data")
        else:  # pragma: no cover
            tar.extractall(lifepak_dir)

    return {
        "zoll": zoll_path,
        "lifepak": lifepak_dir / "LP15_Continuous.xml",
        "lucas": REPO_ROOT / "tests" / "data" / "Lucas_file_Lucas.xml",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--ref", default=DEFAULT_REF, help="git reference to use")
    parser.add_argument(
        "--output-dir", type=Path, default=REPO_ROOT / "tests" / "data" / "golden"
    )
    args = parser.parse_args(argv)
    args.output_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmp:
        tmpdir = Path(tmp)
        worktree = tmpdir / "worktree"
        subprocess.run(
            ["git", "worktree", "add", "--detach", str(worktree), args.ref],
            cwd=REPO_ROOT,
            check=True,
            capture_output=True,
        )
        try:
            cases = _prepare_cases(tmpdir)
            env = os.environ | {
                "PYTHONPATH": os.pathsep.join([str(worktree / "src"), str(REPO_ROOT)])
            }
            for case, recording_path in cases.items():
                output_path = (
                    args.output_dir / f"cprdat_reference_{args.ref}_{case}.json.bz2"
                )
                subprocess.run(
                    [
                        sys.executable,
                        "-c",
                        RUNNER,
                        str(worktree),
                        case,
                        str(recording_path),
                        str(output_path),
                        args.ref,
                    ],
                    cwd=tmpdir,
                    env=env,
                    check=True,
                )
        finally:
            subprocess.run(
                ["git", "worktree", "remove", "--force", str(worktree)],
                cwd=REPO_ROOT,
                check=False,
                capture_output=True,
            )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
