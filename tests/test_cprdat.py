"""Tests for ``Vitals.make_cprdat_analysis`` (German Resuscitation Registry).

``make_cprdat_analysis`` last worked at commit ``b2b678c`` and has been broken
since it was merged into ``main`` (``e148f02``), as the APIs it relies on had
changed in the meantime. Reference outputs of the last working version are
stored in ``tests/data/golden/cprdat_reference_b2b678c_*.json.bz2``
(generated by ``scripts/cprdat_reference.py``).

The tests are expected to fail until the function has been ported to the
current API (refactoring plan, step 1.5).
"""

import bz2
import copy
import json

import pytest

from vitabel import Vitals

from tests.conftest import TEST_DATA_DIR
from tests.golden import GOLDEN_DIR

REFERENCE_REF = "b2b678c"


def _reference(case: str) -> dict:
    path = GOLDEN_DIR / f"cprdat_reference_{REFERENCE_REF}_{case}.json.bz2"
    with bz2.open(path, "rt", encoding="utf-8") as fd:
        return json.load(fd)


@pytest.fixture
def lucas_vitals() -> Vitals:
    recording = Vitals()
    recording.add_defibrillator_recording(TEST_DATA_DIR / "Lucas_file_Lucas.xml")
    return recording


@pytest.mark.parametrize("case", ["zoll", "lifepak", "lucas"])
def test_cprdat_reference_files(case):
    reference = _reference(case)
    assert reference["case"] == case
    assert reference["generated_with"]["git_ref"] == REFERENCE_REF
    assert {"recording_info", "registry_info", "registry_time_points"} <= set(
        reference["result"]
    )


@pytest.mark.xfail(
    strict=True,
    reason="broken since merge e148f02; to be ported in refactoring step 1.5",
)
@pytest.mark.parametrize("case", ["zoll", "lifepak", "lucas"])
def test_cprdat_analysis(case, request):
    if case == "lucas":
        recording = request.getfixturevalue("lucas_vitals")
    else:
        recording = copy.deepcopy(request.getfixturevalue(f"{case}_vitals"))

    result = recording.make_cprdat_analysis()

    reference = _reference(case)["result"]
    assert set(result) == set(reference)
    for key in ["recording_info", "registry_info"]:
        assert set(result[key]) == set(reference[key])
